"use client";

import React, { useState, useEffect, useRef, use } from "react";
import Link from "next/link";
import {
  fetchPublicAgentInfo,
  executePublicChat,
  PublicAgentInfo,
} from "@/lib/api";
import { OtterLogo } from "@/components/OtterLogo";
import {
  Send,
  RefreshCw,
  Sparkles,
  Bot,
  User,
  AlertCircle,
  Clock,
  ArrowLeft,
  Check,
  Copy,
} from "lucide-react";

interface ChatMessage {
  id: string;
  role: "user" | "agent";
  content: string;
  timestamp: string;
  durationMs?: number;
}

export default function PublicChatPage({
  params,
}: {
  params: Promise<{ workflowId: string }>;
}) {
  const resolvedParams = use(params);
  const { workflowId } = resolvedParams;

  const [agentInfo, setAgentInfo] = useState<PublicAgentInfo | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  const [messages, setMessages] = useState<ChatMessage[]>([]);
  const [inputValue, setInputValue] = useState("");
  const [isSending, setIsSending] = useState(false);
  const [copiedLink, setCopiedLink] = useState(false);

  const messagesEndRef = useRef<HTMLDivElement>(null);
  const inputRef = useRef<HTMLInputElement>(null);

  // Scroll to bottom whenever messages change
  useEffect(() => {
    messagesEndRef.current?.scrollIntoView({ behavior: "smooth" });
  }, [messages, isSending]);

  // Load public agent info on mount
  useEffect(() => {
    let isMounted = true;
    setLoading(true);
    setError(null);

    fetchPublicAgentInfo(workflowId)
      .then((data) => {
        if (!isMounted) return;
        setAgentInfo(data);
        // Initialize with agent welcome message
        const welcome =
          data.welcome_message ||
          `Hello! I am ${data.name}. How can I help you today?`;
        setMessages([
          {
            id: "welcome-1",
            role: "agent",
            content: welcome,
            timestamp: new Date().toLocaleTimeString([], {
              hour: "2-digit",
              minute: "2-digit",
            }),
          },
        ]);
      })
      .catch((err) => {
        if (!isMounted) return;
        setError(
          err.message ||
            "Unable to load this AI Agent. It may not exist or has been paused.",
        );
      })
      .finally(() => {
        if (isMounted) setLoading(false);
      });

    return () => {
      isMounted = false;
    };
  }, [workflowId]);

  const handleSendMessage = async (textToSend?: string) => {
    const message = (textToSend ?? inputValue).trim();
    if (!message || isSending) return;

    // Check if workflow is active in local state first
    if (agentInfo?.status !== "active") {
      const errorMsg: ChatMessage = {
        id: `err-${Date.now()}`,
        role: "agent",
        content:
          "⚠️ This agent is currently paused or inactive. Please activate the workflow in Otter Studio before chatting.",
        timestamp: new Date().toLocaleTimeString([], {
          hour: "2-digit",
          minute: "2-digit",
        }),
      };
      setMessages((prev) => [...prev, errorMsg]);
      return;
    }

    const userMsg: ChatMessage = {
      id: `usr-${Date.now()}`,
      role: "user",
      content: message,
      timestamp: new Date().toLocaleTimeString([], {
        hour: "2-digit",
        minute: "2-digit",
      }),
    };

    setMessages((prev) => [...prev, userMsg]);
    setInputValue("");
    setIsSending(true);

    try {
      // 1. Verify workflow is active in PostgreSQL before executing prompt
      let isWorkflowActive = agentInfo.status === "active";
      try {
        const freshInfo = await fetchPublicAgentInfo(workflowId);
        setAgentInfo(freshInfo);
        isWorkflowActive = freshInfo.status === "active";
      } catch (checkErr: any) {
        // If checking status fails, proceed to execution which validates on backend
      }

      if (!isWorkflowActive) {
        const errorMsg: ChatMessage = {
          id: `err-${Date.now()}`,
          role: "agent",
          content:
            "⚠️ This agent is currently paused by its creator. Please activate the workflow in Otter Studio to chat.",
          timestamp: new Date().toLocaleTimeString([], {
            hour: "2-digit",
            minute: "2-digit",
          }),
        };
        setMessages((prev) => [...prev, errorMsg]);
        return;
      }

      // 2. Workflow is confirmed active: execute with user prompt
      const res = await executePublicChat(workflowId, message);
      console.log(res);
      const agentMsg: ChatMessage = {
        id: res.execution_id || `agent-${Date.now()}`,
        role: "agent",
        content: res.response || "No reply was generated by the agent.",
        timestamp: new Date().toLocaleTimeString([], {
          hour: "2-digit",
          minute: "2-digit",
        }),
        durationMs: res.duration_ms,
      };
      setMessages((prev) => [...prev, agentMsg]);
    } catch (err: any) {
      const errorMsg: ChatMessage = {
        id: `err-${Date.now()}`,
        role: "agent",
        content: `Error: ${err.message || "Failed to process request."}`,
        timestamp: new Date().toLocaleTimeString([], {
          hour: "2-digit",
          minute: "2-digit",
        }),
      };
      setMessages((prev) => [...prev, errorMsg]);
    } finally {
      setIsSending(false);
      setTimeout(() => inputRef.current?.focus(), 50);
    }
  };

  const handleCopyLink = () => {
    if (typeof window !== "undefined") {
      navigator.clipboard.writeText(window.location.href);
      setCopiedLink(true);
      setTimeout(() => setCopiedLink(false), 2000);
    }
  };

  if (loading) {
    return (
      <div className="min-h-screen bg-[#060911] text-slate-100 flex flex-col items-center justify-center p-4">
        <RefreshCw className="w-8 h-8 text-cyan-400 animate-spin mb-4" />
        <h2 className="text-base font-semibold text-white">
          Connecting to Agent...
        </h2>
        <p className="text-xs text-slate-400 mt-1 font-mono">
          Loading workflow deployment configuration
        </p>
      </div>
    );
  }

  if (error || !agentInfo) {
    return (
      <div className="min-h-screen bg-[#060911] text-slate-100 flex flex-col items-center justify-center p-6">
        <div className="max-w-md w-full bg-slate-900/60 border border-slate-800 rounded-2xl p-6 text-center shadow-xl">
          <div className="w-12 h-12 rounded-2xl bg-rose-500/10 border border-rose-500/20 text-rose-400 flex items-center justify-center mx-auto mb-4">
            <AlertCircle className="w-6 h-6" />
          </div>
          <h2 className="text-lg font-bold text-white mb-2">
            Agent Unavailable
          </h2>
          <p className="text-xs text-slate-400 leading-relaxed mb-6">
            {error ||
              "This AI Agent is currently inactive or paused by its creator."}
          </p>
          <Link
            href="/"
            className="inline-flex items-center gap-2 px-4 py-2 bg-slate-800 hover:bg-slate-750 text-slate-200 hover:text-white rounded-xl text-xs font-semibold transition-all"
          >
            <ArrowLeft className="w-4 h-4" />
            <span>Return to Otter Home</span>
          </Link>
        </div>
      </div>
    );
  }

  const isPaused = agentInfo.status === "paused";

  return (
    <div className="min-h-screen bg-[#060911] text-slate-100 flex flex-col font-sans selection:bg-cyan-500/20 selection:text-cyan-300">
      {/* 1. Header Bar */}
      <header className="border-b border-slate-800/80 bg-[#0a0f1d]/90 backdrop-blur-md px-4 sm:px-6 py-3 flex items-center justify-between sticky top-0 z-30">
        <div className="flex items-center gap-3 min-w-0">
          <div className="w-9 h-9 rounded-xl bg-linear-to-tr from-cyan-500 to-indigo-500 p-0.5 flex items-center justify-center shrink-0 shadow-md shadow-cyan-500/10">
            <div className="w-full h-full bg-[#060911] rounded-[10px] flex items-center justify-center">
              <Bot className="w-5 h-5 text-cyan-400" />
            </div>
          </div>
          <div className="min-w-0">
            <div className="flex items-center gap-2">
              <h1 className="text-sm font-bold text-white truncate">
                {agentInfo.name}
              </h1>
              {isPaused ? (
                <span className="px-2 py-0.5 rounded-full text-[10px] font-medium bg-amber-500/10 text-amber-400 border border-amber-500/30">
                  Paused
                </span>
              ) : (
                <span className="px-2 py-0.5 rounded-full text-[10px] font-medium bg-emerald-500/10 text-emerald-400 border border-emerald-500/30 flex items-center gap-1">
                  <span className="w-1.5 h-1.5 rounded-full bg-emerald-400 animate-pulse" />
                  Active
                </span>
              )}
            </div>
            <p className="text-[11px] text-slate-400 truncate max-w-sm sm:max-w-md">
              {agentInfo.description || "Autonomous AI Agent built with Otter"}
            </p>
          </div>
        </div>

        <div className="flex items-center gap-2">
          <button
            onClick={handleCopyLink}
            className="flex items-center gap-1.5 text-xs text-slate-400 hover:text-white px-2.5 py-1.5 rounded-lg bg-slate-900 border border-slate-800 hover:border-slate-700 transition-colors"
            title="Copy shareable link"
          >
            {copiedLink ? (
              <>
                <Check className="w-3.5 h-3.5 text-emerald-400" />
                <span className="hidden sm:inline text-emerald-400">
                  Copied
                </span>
              </>
            ) : (
              <>
                <Copy className="w-3.5 h-3.5" />
                <span className="hidden sm:inline">Share</span>
              </>
            )}
          </button>
        </div>
      </header>

      {/* Paused Warning Banner */}
      {isPaused && (
        <div className="bg-amber-500/10 border-b border-amber-500/20 px-4 py-2 flex items-center justify-center gap-2 text-xs text-amber-300">
          <AlertCircle className="w-4 h-4 shrink-0" />
          <span>
            This agent is currently paused by its creator and may not respond to
            queries.
          </span>
        </div>
      )}

      {/* 2. Messages Container */}
      <main className="flex-1 max-w-3xl w-full mx-auto px-4 py-6 flex flex-col justify-between overflow-y-auto">
        <div className="space-y-4 mb-6">
          {messages.map((msg) => {
            const isUser = msg.role === "user";
            return (
              <div
                key={msg.id}
                className={`flex gap-3 ${isUser ? "justify-end" : "justify-start"}`}
              >
                {!isUser && (
                  <div className="w-7 h-7 rounded-lg bg-cyan-500/10 border border-cyan-500/30 flex items-center justify-center shrink-0 mt-0.5 text-cyan-400">
                    <Sparkles className="w-3.5 h-3.5" />
                  </div>
                )}

                <div
                  className={`max-w-[85%] sm:max-w-[75%] rounded-2xl px-4 py-3 text-sm leading-relaxed ${
                    isUser
                      ? "bg-cyan-600 text-white rounded-tr-xs shadow-md shadow-cyan-600/20"
                      : "bg-slate-900/90 border border-slate-800/80 text-slate-200 rounded-tl-xs shadow-sm"
                  }`}
                >
                  <div className="whitespace-pre-wrap font-sans">
                    {msg.content}
                  </div>
                  <div
                    className={`flex items-center gap-2 mt-1.5 text-[10px] ${
                      isUser ? "text-cyan-200" : "text-slate-500"
                    }`}
                  >
                    <span>{msg.timestamp}</span>
                    {msg.durationMs && (
                      <span className="flex items-center gap-0.5">
                        <Clock className="w-2.5 h-2.5" />
                        {msg.durationMs}ms
                      </span>
                    )}
                  </div>
                </div>

                {isUser && (
                  <div className="w-7 h-7 rounded-lg bg-slate-800 border border-slate-700 flex items-center justify-center shrink-0 mt-0.5 text-slate-300">
                    <User className="w-3.5 h-3.5" />
                  </div>
                )}
              </div>
            );
          })}

          {/* Typing / Processing indicator */}
          {isSending && (
            <div className="flex gap-3 justify-start items-center">
              <div className="w-7 h-7 rounded-lg bg-cyan-500/10 border border-cyan-500/30 flex items-center justify-center shrink-0 text-cyan-400">
                <RefreshCw className="w-3.5 h-3.5 animate-spin" />
              </div>
              <div className="bg-slate-900/90 border border-slate-800 px-4 py-2.5 rounded-2xl text-xs text-slate-400 flex items-center gap-2">
                <span>Agent is thinking and processing tools...</span>
              </div>
            </div>
          )}

          <div ref={messagesEndRef} />
        </div>

        {/* 3. Starter Suggestions (Chips) */}
        {messages.length <= 2 &&
          agentInfo.sample_prompts &&
          agentInfo.sample_prompts.length > 0 && (
            <div className="mb-4">
              <div className="text-[11px] font-medium text-slate-400 mb-2">
                Suggested Prompts:
              </div>
              <div className="flex flex-wrap gap-2">
                {agentInfo.sample_prompts.map((prompt, idx) => (
                  <button
                    key={idx}
                    onClick={() => handleSendMessage(prompt)}
                    disabled={isSending || isPaused}
                    className="text-xs px-3 py-1.5 rounded-xl bg-slate-900 border border-slate-800 hover:border-cyan-500/50 hover:bg-slate-800/80 text-slate-300 hover:text-white transition-all text-left cursor-pointer disabled:opacity-50"
                  >
                    💡 {prompt}
                  </button>
                ))}
              </div>
            </div>
          )}

        {/* 4. Chat Input Bar */}
        <div className="sticky bottom-4 z-20">
          <form
            onSubmit={(e) => {
              e.preventDefault();
              handleSendMessage();
            }}
            className="flex items-center gap-2 bg-[#0c1222] border border-slate-800/90 rounded-2xl p-2 shadow-2xl focus-within:border-cyan-500/80 transition-all"
          >
            <input
              ref={inputRef}
              type="text"
              value={inputValue}
              onChange={(e) => setInputValue(e.target.value)}
              disabled={isSending || isPaused}
              placeholder={
                isPaused
                  ? "Agent is currently paused..."
                  : `Ask ${agentInfo.name}...`
              }
              className="flex-1 bg-transparent px-3 py-1.5 text-sm text-white placeholder-slate-500 focus:outline-none disabled:opacity-50 font-sans"
            />
            <button
              type="submit"
              disabled={!inputValue.trim() || isSending || isPaused}
              className="px-4 py-2 bg-gradient-to-r from-cyan-500 to-indigo-500 hover:brightness-110 disabled:opacity-30 disabled:pointer-events-none text-white rounded-xl text-xs font-semibold transition-all flex items-center gap-1.5 shadow-md shadow-cyan-500/20 cursor-pointer"
            >
              {isSending ? (
                <RefreshCw className="w-3.5 h-3.5 animate-spin" />
              ) : (
                <Send className="w-3.5 h-3.5" />
              )}
              <span className="hidden sm:inline">Send</span>
            </button>
          </form>
          <div className="flex items-center justify-between mt-2 px-2 text-[10px] text-slate-500">
            <span>Powered by Otter Autonomous Agent Workflow Engine</span>
            <span>Model: {agentInfo.model}</span>
          </div>
        </div>
      </main>
    </div>
  );
}
